import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Float16Array } from '@petamoriken/float16';
const path=process.argv[2];
assert(path,'Pass a retained CUA GPU diagnostics JSON/AX text file');
const text=readFileSync(path,'utf8');
const data=JSON.parse(text.slice(text.indexOf('{'),text.lastIndexOf('}')+1));
assert.deepEqual(data.camera,[0,0,0],'Oracle requires Load synthetic scene identity camera');
assert.equal(data.visible,4); assert.deepEqual([...data.indices].sort(),[0,1,2,3]);
assert.equal(data.indices[0],2); assert.equal(data.indices[3],3);
const half=value=>new Float16Array([value])[0];
const focal=.5*data.viewport[1]/Math.tan(Math.PI/8);
const x=half(-.7), z=3;
const scale=Number(process.argv[3]??1);
const sx=Math.exp(half(Math.log(.12)))*scale;
const sy=Math.exp(half(Math.log(.3)))*scale;
const xx=(focal*sx/z)**2+(focal*x*sx/z**2)**2+.3;
const yy=(focal*sy/z)**2+.3;
const expectedConic=[1/xx,0,1/yy];
const actualConic=data.splats.slice(4,7);
const relativeError=Math.max(...actualConic.map((v,i)=>Math.abs(v-expectedConic[i])/Math.max(1e-8,Math.abs(expectedConic[i]))));
assert(relativeError<.001,'GPU conic disagrees with independent perspective covariance reference');
const radius=Math.ceil(3*Math.sqrt(Math.max(xx,yy)));
assert(Math.abs(data.splats[2]-radius)<=1,'GPU eigenvalue radius disagrees');
assert(Math.abs(data.splats[0]-2*focal*x/(z*data.viewport[0]))<1e-5,'GPU projected center disagrees');
assert(data.splats[17]<0,'45 degree rotated anisotropic lobe must have a negative inverse-conic cross term');
const red=1-.4886025119029199*.25*x/Math.hypot(x,z);
assert(Math.abs(data.splats[8]-red)<.002,'GPU view-dependent first-order SH disagrees');
assert(data.samples.length===4&&data.samples.every(s=>s.actual.every((v,i)=>Math.abs(v-s.expected[i])<.012)),'Actual GPU pixels disagree with conic alpha-compositing reference');
console.log(JSON.stringify({status:'pass',viewport:data.viewport,visible:data.visible,indices:data.indices,expectedConic,actualConic,relativeError,expectedRadius:radius,actualRadius:data.splats[2],expectedSHRed:red,actualSHRed:data.splats[8],maxPixelError:Math.max(...data.samples.map(s=>s.error))},null,2));
